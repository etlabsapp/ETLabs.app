function killProc(st: SState, pr: Proc, meta: Meta, e: (t: string) => void): void {
  if (pr.pid === 1 || pr.pid === 2) { e(`(sim) Killing PID ${pr.pid} would take the whole server down, so it isn't simulated.`); return; }
  if (pr.pid === 1187 || pr.pid === 1190 || pr.pid === 1191) { meta.logout = "1"; return; }
  st.procs = st.procs.filter((p) => p.pid !== pr.pid);
  for (const k of Object.keys(st.services)) if (st.services[k].pid === pr.pid) st.services[k].active = false;
}

/* ================= Filters (pipes) ================= */
function filt(v: string, args: string[], input: string[] | null, st: SState, w: World, user: string, meta: Meta): Line[] {
  const L: Line[] = [];
  const o = (t: string) => { L.push({ text: t, kind: "out" }); };
  const e = (t: string) => { L.push({ text: t, kind: "err" }); };
  const fl = flagsOf(args);
  let num = 10;
  const rest: string[] = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if ((v === "head" || v === "tail") && a === "-n") { num = parseInt(args[++i] ?? "10", 10); continue; }
    if ((v === "head" || v === "tail") && /^-\d+$/.test(a)) { num = parseInt(a.slice(1), 10); continue; }
    if (/^-[A-Za-z]+$/.test(a) && !(v === "tr")) continue;
    rest.push(a);
  }
  let pat = "", set1 = "", set2 = "";
  if (v === "grep") { pat = rest.shift() ?? ""; if (!pat) { e("Usage: grep [OPTION]... PATTERNS [FILE]..."); return L; } meta.grep = pat; }
  if (v === "tr") { set1 = rest.shift() ?? ""; set2 = rest.shift() ?? ""; }
  let inp: string[] = input ?? [];
  if (v === "tee") { const data = inp.join("\n") + (inp.length ? "\n" : ""); for (const a of rest) { const err = writeFile(st, w, norm(w.cwd, a), data, fl.includes("a"), user, stamp()); if (err) e(`tee: ${a}: ${err}`); } inp.forEach(o); meta.tee = "1"; return L; }
  if (input === null) {
    if (!rest.length) { L.push({ text: `(sim) ${v} needs a file name or piped input here.`, kind: "sys" }); return L; }
    inp = [];
    for (const a of rest) {
      const p = norm(w.cwd, a); const n = st.fs[follow(st, p)];
      if (!n) { e(`${v}: ${a}: No such file or directory`); continue; }
      if (n.type === "dir") { e(`${v}: ${a}: Is a directory`); continue; }
      if (!reach(st, p, user) || !can(st, n, user, 4)) { e(`${v}: ${a}: Permission denied`); continue; }
      const c = readContent(st, p); inp.push(...(c ? c.replace(/\n$/, "").split("\n") : []));
    }
  }
  if (!meta[v]) meta[v] = "1";
  if (v === "grep") {
    let re: RegExp | null = null;
    try { re = new RegExp(pat, fl.includes("i") ? "i" : ""); } catch (_e) { re = null; }
    const r2 = re;
    const hits = inp.filter((x) => (r2 ? r2.test(x) : x.includes(pat)) !== fl.includes("v"));
    if (fl.includes("c")) o(String(hits.length)); else hits.forEach(o);
  } else if (v === "sort") {
    const key = (x: string) => { const m = x.trim().match(/^([\d.]+)([KMGT]?)/); return m ? parseFloat(m[1]) * Math.pow(1024, " KMGT".indexOf(m[2] || " ")) : 0; };
    const numeric = fl.includes("h") || fl.includes("n");
    const r = [...inp].sort((a, b) => (numeric ? key(a) - key(b) : a.localeCompare(b)));
    if (fl.includes("r")) r.reverse();
    r.forEach(o);
  } else if (v === "head") inp.slice(0, num).forEach(o);
  else if (v === "tail") { inp.slice(-num).forEach(o); if (fl.includes("f")) L.push({ text: "(sim) -f would keep following new lines until Ctrl+C.", kind: "sys" }); }
  else if (v === "wc") {
    const words = inp.join(" ").split(/\s+/).filter((x) => x).length, chars = inp.reduce((t, x) => t + x.length + 1, 0);
    const tail = input === null ? " " + rest.join(" ") : "";
    o(fl.includes("l") ? `${inp.length}${tail}` : fl.includes("w") ? `${words}${tail}` : fl.includes("c") ? `${chars}${tail}` : `${String(inp.length).padStart(7)} ${String(words).padStart(7)} ${String(chars).padStart(7)}${tail}`);
  } else if (v === "tr") {
    const ex = (s: string) => s.replace(/(\w)-(\w)/g, (_m: string, a: string, b: string) => { let r = ""; for (let c = a.charCodeAt(0); c <= b.charCodeAt(0); c++) r += String.fromCharCode(c); return r; });
    const s1 = ex(set1), s2 = ex(set2);
    inp.forEach((x) => o(x.split("").map((ch) => { const i = s1.indexOf(ch); return i < 0 || !s2 ? ch : s2.charAt(Math.min(i, s2.length - 1)); }).join("")));
  }
  return L;
}
const flagsOf = (args: string[]): string => args.filter((a) => /^-[A-Za-z]+$/.test(a)).map((a) => a.slice(1)).join("");
const operands = (args: string[]): string[] => args.filter((a) => !/^-[A-Za-z]+$/.test(a));

