export function passesTask(missionIndex: number, step: number, before: World, after: World, res: { lines: Line[]; meta: Meta }): boolean {
  const cur = MISSIONS[missionIndex]?.tasks[step];
  if (!cur || cur.ans) return false;
  const home = MISSIONS[missionIndex].home;
  if (home && after.host !== home) return false;
  const ctx: Ctx = {
    verb: res.meta.verb ?? "",
    cmds: (res.meta.cmds ?? "").split("\n"),
    ok: !res.lines.some((l) => l.kind === "err"),
    host: after.host,
    prevHost: before.host,
    cwd: after.cwd,
    prevCwd: before.cwd,
    st: after.host ? after.servers[after.host] : null,
    w: after,
    meta: res.meta,
  };
  return cur.check(ctx);
}

export function passesAnswer(missionIndex: number, step: number, cmd: string): boolean {
  const cur = MISSIONS[missionIndex]?.tasks[step];
  if (!cur?.ans) return false;
  const n = normAns(cmd);
  return cur.ans.some((a) => (typeof a === "string" ? a === n : a.test(n)));
}

